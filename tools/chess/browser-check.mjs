import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { startTestHost } from './test-host.mjs'
import { state, leaveHome, clickSquare as clickHelper } from './browser-helpers.mjs'

const host = await startTestHost()
const browser = await chromium.launch()
const errors = []
const directory = new URL('../../test-results/chess/', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')
await mkdir(directory, { recursive: true })
try {
  const white = await browser.newPage({ viewport: { width: 420, height: 600 } })
  const black = await browser.newPage({ viewport: { width: 420, height: 600 } })
  for (const page of [white, black]) {
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', event => {
      if (event.type() === 'error' && !event.text().includes('503')) errors.push(event.text())
    })
  }
  const clickSquare = (page, square) => clickHelper(page, square)
  const recovering = host.holdRecovery()
  await white.goto(host.url + '/?player=w')
  await white.locator('#app[aria-busy=false]').waitFor(); await leaveHome(white)
  await white.locator('#bot-button').click()
  await white.locator('#bot-enabled').uncheck()
  await white.locator('[aria-label="Cerrar Dex"]').click()
  await white.locator('[data-side=w]').click()
  await clickSquare(white, 'e2'); await clickSquare(white, 'e4')
  assert.deepEqual((await state(white)).moves, ['e2e4'])
  await white.locator('#undo').click()
  assert.deepEqual((await state(white)).moves, [])
  await white.locator('#redo').click()
  assert.deepEqual((await state(white)).moves, ['e2e4'])
  await white.screenshot({ path: directory + '/local.png' })

  await white.locator('#online-button').click()
  await white.locator('#online-signin').click()
  // Lobby: the list shows the caller first, then free players, then people already in a game.
  await white.locator('#presence-list .presence-row:not(.is-skeleton)').first().waitFor()
  const lobby = (await state(white)).online.presence
  assert.equal(lobby.status, 'ready')
  assert.deepEqual(lobby.players.map(p => p.name), ['Alfil Azul', 'Lucía Ferrer', 'Marisol Vega', 'Tomás Quiroga'])
  assert.equal(lobby.players[0].self, true)
  assert.equal(await white.locator('#presence-count').textContent(), '4 conectados')
  await white.waitForTimeout(350)
  await white.screenshot({ path: directory + '/presence.png' })
  // A second person signs in and appears on the next refresh, without reloading the panel.
  const arrival = await browser.newPage({ viewport: { width: 420, height: 600 } })
  await arrival.goto(host.url + '/?player=b')
  await arrival.locator('#app[aria-busy=false]').waitFor(); await leaveHome(arrival)
  await arrival.locator('#online-button').click()
  await arrival.locator('#online-signin').click()
  await arrival.locator('#presence-count').filter({ hasText: '5 conectados' }).waitFor()
  await white.waitForTimeout(5200)
  await white.locator('#online-button').click()
  await white.locator('#online-button').click()
  await white.locator('#presence-count').filter({ hasText: '5 conectados' }).waitFor()
  assert.ok((await state(white)).online.presence.players.some(p => p.name === 'Torre Roja' && !p.self))
  await arrival.close()
  await white.locator('#online-create').click()
  await white.locator('#online-code-display').filter({ hasText: 'ABC123' }).waitFor()
  assert.equal(await white.locator('#online-presence').isHidden(), true)
  recovering.release()
  await white.waitForTimeout(150)
  assert.equal((await state(white)).online.phase, 'waiting')
  await white.screenshot({ path: directory + '/waiting.png' })
  assert.equal((await state(white)).canMove, false)
  await white.locator('[aria-label="Cerrar online"]').click()

  await black.goto(host.url + '/?player=b&theme=light')
  await black.locator('#app[aria-busy=false]').waitFor(); await leaveHome(black)
  await black.locator('#online-button').click()
  await black.locator('#online-signin').click()
  await black.locator('#online-code').fill('abc123')
  await black.locator('#online-join').click()
  await black.locator('#online-room-status').filter({ hasText: 'Partida en curso' }).waitFor()
  await black.locator('[aria-label="Cerrar online"]').click()
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).canMove, null, { timeout: 9000 })
  for (const id of ['undo', 'redo', 'hint', 'bot-button', 'restart', 'drawer-toggle']) assert.equal(await white.locator('#' + id).isDisabled(), true)
  await clickSquare(white, 'e2'); await clickSquare(white, 'e4')
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).moves.length === 1)
  await black.waitForFunction(() => JSON.parse(window.render_game_to_text()).moves.length === 1, null, { timeout: 9000 })
  await clickSquare(black, 'e7', true); await clickSquare(black, 'e5', true)
  await black.waitForFunction(() => JSON.parse(window.render_game_to_text()).moves.length === 2)
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).moves.length === 2, null, { timeout: 9000 })
  assert.equal((await state(white)).fen, (await state(black)).fen)
  await white.screenshot({ path: directory + '/online-dark.png' })
  await black.screenshot({ path: directory + '/online-light.png' })

  host.setOffline(true)
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).online.phase === 'disconnected', null, { timeout: 9000 })
  assert.equal((await state(white)).canMove, false)
  await white.locator('#online-button').click()
  await white.screenshot({ path: directory + '/disconnected.png' })
  host.setOffline(false)
  await white.locator('#online-retry').click()
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).online.phase === 'active')
  await white.locator('#online-local').click()
  assert.equal((await state(white)).mode, 'local')
  assert.deepEqual((await state(white)).moves, ['e2e4'])
  await white.locator('#online-button').click()
  await white.locator('#online-signin').click()
  await white.locator('#online-resume').click()
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).mode === 'online')
  assert.deepEqual((await state(white)).moves, ['e2e4', 'e7e5'])
  await white.evaluate(() => window.__testEmit('account', { signedIn: false }))
  assert.equal((await state(white)).canMove, false)
  assert.equal(await white.locator('#online-signin').isVisible(), true)
  await white.locator('#online-local').click()

  // Reload recovers the local save and last room, not an access token.
  await white.reload()
  await white.locator('#app[aria-busy=false]').waitFor(); await leaveHome(white)
  assert.deepEqual((await state(white)).moves, ['e2e4'])
  assert.ok(!JSON.stringify([...host.stores.values()]).includes('test-player'))
  await white.setViewportSize({ width: 320, height: 480 })
  await white.locator('#online-button').click()
  await white.locator('#online-sheet').waitFor({ state: 'visible' })
  await white.waitForTimeout(250)
  await white.screenshot({ path: directory + '/compact.png' })
  assert.equal(await white.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)

  await white.locator('#online-signin').click()
  await white.locator('#online-resume').click()
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).online.phase === 'active')
  const refresh = host.holdWhiteRefresh()
  await refresh.arrived
  await white.evaluate(() => window.__testEmit('visibility', { visible: false }))
  host.finishGame()
  refresh.release()
  await white.waitForFunction(() => JSON.parse(window.render_game_to_text()).phase === 'over')
  await white.evaluate(() => window.__testEmit('visibility', { visible: true }))
  assert.equal((await state(white)).moves.length, 7)
  await white.locator('[aria-label="Cerrar online"]').click()
  await white.waitForTimeout(1200)
  await white.screenshot({ path: directory + '/finished.png' })
  await white.locator('#result-local').click()
  assert.equal((await state(white)).mode, 'local')

  host.stores.set('/storage/p/settings', { botEnabled: false })
  host.stores.set('/storage/p/game', { side: 'w', start: '7k/P7/8/8/8/8/8/7K w - - 0 1', moves: [], cursor: 0 })
  const promotion = await browser.newPage({ viewport: { width: 420, height: 600 } })
  await promotion.goto(host.url + '/?player=p')
  await promotion.locator('#app[aria-busy=false]').waitFor(); await leaveHome(promotion)
  await clickSquare(promotion, 'a7'); await clickSquare(promotion, 'a8')
  await promotion.locator('[data-promotion=n]').click()
  assert.ok((await state(promotion)).fen.startsWith('N6k/'))
  assert.deepEqual((await state(promotion)).moves, ['a7a8n'])
  await promotion.waitForTimeout(300)
  await promotion.screenshot({ path: directory + '/promotion.png' })
  // Empty lobby and an outage while the sheet is open: keep the last list, say it is stale.
  host.setOthers([])
  const lobbyOnly = await browser.newPage({ viewport: { width: 420, height: 505 } })
  lobbyOnly.on('pageerror', error => errors.push(error.message))
  await lobbyOnly.goto(host.url + '/?player=w&theme=light')
  await lobbyOnly.locator('#app[aria-busy=false]').waitFor(); await leaveHome(lobbyOnly)
  await lobbyOnly.locator('#online-button').click()
  await lobbyOnly.locator('#online-signin').click()
  await lobbyOnly.locator('#presence-note').filter({ hasText: 'no hay nadie más' }).waitFor()
  await lobbyOnly.waitForTimeout(300)
  await lobbyOnly.screenshot({ path: directory + '/presence-empty.png' })
  host.setOthers([{ id: 'p_marisol', name: 'Marisol Vega', status: 'available', self: false }])
  await lobbyOnly.waitForTimeout(5200)
  host.setOffline(true)
  await lobbyOnly.locator('#online-button').click()
  await lobbyOnly.locator('#online-button').click()
  await lobbyOnly.locator('#presence-note').filter({ hasText: 'No se pudo actualizar la lista' }).waitFor()
  assert.equal((await state(lobbyOnly)).online.presence.status, 'error')
  assert.equal(await lobbyOnly.locator('#online-create').isEnabled(), true)
  await lobbyOnly.screenshot({ path: directory + '/presence-error.png' })
  host.setOffline(false)
  const unconfigured = await browser.newPage({ viewport: { width: 420, height: 505 } })
  await unconfigured.route('**/online-config.js', route => route.fulfill({ contentType: 'text/javascript', body: 'export const onlineConfig = { apiUrl: null }' }))
  await unconfigured.goto(host.url + '/?player=unconfigured')
  await unconfigured.locator('#app[aria-busy=false]').waitFor(); await leaveHome(unconfigured)
  await unconfigured.locator('#online-button').click()
  await unconfigured.waitForTimeout(250)
  assert.equal(await unconfigured.locator('#online-signin').isDisabled(), true)
  assert.match(await unconfigured.locator('#online-message').textContent(), /conecte el servidor/)
  await unconfigured.screenshot({ path: directory + '/unconfigured.png' })
  assert.deepEqual(errors, [])
  console.log('PASS browser: local/undo/redo, two players, turn guards, matching boards, outage/reconnect, local preservation, recovery, revocation, startup/visibility races, promotion, unconfigured state, compact layout. TEST service only.')
} catch (error) {
  for (const context of browser.contexts()) for (const page of context.pages()) {
    console.error(await page.locator('#online-message').textContent(), await page.evaluate(() => window.render_game_to_text?.()))
  }
  console.error('Browser errors:', errors)
  throw error
} finally { await browser.close(); await host.close() }
